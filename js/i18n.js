  let lang = "ko";

  function setLang(l) { lang = dict[l] ? l : "ko"; }

  function t(key, params) {
    let s = dict[lang][key] ?? dict.ko[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  }

  // data-i18n 속성이 붙은 모든 요소의 텍스트를 갱신한다
  function apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const text = t(el.dataset.i18nPlaceholder);
      el.placeholder = text;       // <input>/<textarea>
      el.dataset.placeholder = text; // contenteditable(rich-field) 등 placeholder 속성이 없는 요소용
    });
    root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
    document.documentElement.lang = lang;
  }

  return { t, setLang, apply, get lang() { return lang; } };
